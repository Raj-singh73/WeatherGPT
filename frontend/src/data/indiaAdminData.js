// 3. Live India-Wide Village & Block Geocoding API Query
export const searchLiveIndiaVillage = async (query) => {
  if (!query || query.trim().length < 2) return [];
  try {
    const url = `https://geocoding-api.open-meteo.com/v1/search?name=${encodeURIComponent(query.trim())}&count=15&country_code=IN&format=json&language=en`;
    const res = await fetch(url);
    if (!res.ok) return [];
    const data = await res.json();
    return (data.results || []).map(r => ({
      name: r.name,
      label: `${r.name}${r.admin3 ? `, ${r.admin3} Block` : ''}, ${r.admin2 || ''} (${r.admin1 || ''})`,
      village: r.name,
      block: r.admin3 || '',
      district: (r.admin2 || '').replace(/ district/i, ''),
      state: r.admin1 || '',
      lat: r.latitude,
      lon: r.longitude,
      elevation: r.elevation || 240,
      source: 'Live Geocoding API'
    }));
  } catch (err) {
    console.warn('Geocoding search notice:', err);
    return [];
  }
};

// 4. India Postal PIN Code Lookup API (Covers all 155,000+ Post Offices / Gram Panchayats)
export const lookupIndiaPincode = async (pincode) => {
  const pin = (pincode || '').toString().trim();
  if (!/^[1-9][0-9]{5}$/.test(pin)) return [];
  try {
    const res = await fetch(`https://api.postalpincode.in/pincode/${pin}`);
    if (!res.ok) return [];
    const json = await res.json();
    if (!json || !json[0] || json[0].Status !== 'Success') return [];
    const offices = json[0].PostOffice || [];
    return offices.map(po => ({
      name: po.Name,
      label: `${po.Name} (${po.Block !== 'NA' && po.Block ? po.Block + ' Block, ' : ''}${po.District}, ${po.State})`,
      village: po.Name,
      block: po.Block !== 'NA' ? po.Block : '',
      district: po.District,
      state: po.State,
      pincode: pin,
      source: 'India Post Directory'
    }));
  } catch (err) {
    console.warn('Postal PIN code lookup notice:', err);
    return [];
  }
};

// 5. Dynamic District Villages & Sub-divisions Fetcher (Covers all blocks and villages in ANY selected district)
const districtCache = {};
export const fetchDistrictVillagesAndBlocks = async (districtName, stateName) => {
  if (!districtName) return { villages: [], blocks: [] };
  const clean = districtName.replace(/\(.*?\)/g, '').replace(/ district/i, '').trim();
  if (districtCache[clean]) return districtCache[clean];

  try {
    const res = await fetch(`https://api.postalpincode.in/postoffice/${encodeURIComponent(clean)}`);
    if (res.ok) {
      const data = await res.json();
      if (data && data[0]?.Status === 'Success') {
        const offices = data[0].PostOffice || [];
        const rawVillages = offices.map(p => p.Name).filter(Boolean);
        const uniqueVillages = Array.from(new Set(rawVillages)).sort();

        const rawBlocks = offices.map(p => p.Block || p.Taluk || p.Division).filter(b => b && b !== 'NA');
        const uniqueBlocks = Array.from(new Set(rawBlocks)).sort();

        const result = {
          villages: uniqueVillages.map(v => ({ name: v, elevation: 250 })),
          blocks: uniqueBlocks.length > 0 ? uniqueBlocks : [`${clean} Central Tehsil`, `${clean} Rural Block`]
        };
        districtCache[clean] = result;
        return result;
      }
    }
  } catch (err) {
    console.warn('District fetch error:', err);
  }

  // Fallback if offline
  return {
    villages: [{ name: `${clean} Kasba`, elevation: 250 }, { name: `${clean} Rural Gram Panchayat`, elevation: 255 }],
    blocks: [`${clean} Tehsil`, `${clean} Block`]
  };
};

// 6. High-Accuracy Dual GPS Reverse Geocoding (Nominatim + BigDataCloud)
export const reverseGeocodeExact = async (lat, lon) => {
  // 1. First Attempt: OpenStreetMap Nominatim
  try {
    const res = await fetch(`https://nominatim.openstreetmap.org/reverse?lat=${lat}&lon=${lon}&format=json&addressdetails=1&zoom=18`, {
      headers: { 'Accept-Language': 'en' }
    });
    if (res.ok) {
      const d = await res.json();
      const a = d.address || {};
      const village = a.village || a.hamlet || a.suburb || a.town || a.neighbourhood || a.locality || a.city_district;
      const block = a.county || a.subdistrict || a.taluk || a.tehsil || a.block || a.state_district;
      const district = (a.state_district || a.county || a.city || '').replace(/ district/i, '');
      const state = a.state;
      if (district || state) {
        return {
          name: `${village || district} (${district || state})`,
          village: village || `${district} Village`,
          block: block || `${district} Tehsil`,
          district: district || 'Local District',
          state: state || 'India',
          lat,
          lon,
          postcode: a.postcode || '',
          elevation: 250,
          source: 'OpenStreetMap High-Accuracy GPS'
        };
      }
    }
  } catch (e) {
    console.warn('Nominatim reverse notice:', e);
  }

  // 2. Second Attempt: BigDataCloud Reverse Geocoding Client
  try {
    const res2 = await fetch(`https://api.bigdatacloud.net/data/reverse-geocode-client?latitude=${lat}&longitude=${lon}&localityLanguage=en`);
    if (res2.ok) {
      const d2 = await res2.json();
      const village = d2.locality || d2.city || 'Local Village';
      const adminList = d2.localityInfo?.administrative || [];
      const talukObj = adminList.find(a => /taluk|tehsil|mandal|block|sub-district/i.test(a.name || a.description));
      const distObj = adminList.find(a => /district/i.test(a.name || a.description));
      const district = (distObj?.name || d2.city || '').replace(/ district/i, '');
      const block = talukObj?.name || `${district} Block`;
      const state = d2.principalSubdivision || 'India';
      return {
        name: `${village} (${district || state})`,
        village,
        block,
        district: district || 'Local District',
        state,
        lat,
        lon,
        elevation: 250,
        source: 'BigDataCloud High-Accuracy GPS'
      };
    }
  } catch (e2) {
    console.warn('BigDataCloud reverse notice:', e2);
  }

  return {
    name: `GPS Point (${lat.toFixed(4)}°N, ${lon.toFixed(4)}°E)`,
    village: 'Local Village',
    block: 'Local Block',
    district: 'Local District',
    state: 'India',
    lat,
    lon,
    elevation: 250,
    source: 'Raw GPS Coordinates'
  };
};

